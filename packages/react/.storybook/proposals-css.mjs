// Writes proposals.scss from every v12 component's proposals/tokens.json: each
// token's per-theme value (`carbon.themes`) as a custom property on the theme's
// selectors. An alias (`{layer-01}`) becomes `var(--cds-layer-01)`. An OKLCH
// value is written as its hex fallback (`com.ibm.harness.fallback`), then as
// OKLCH where the browser supports it. A v12 theme takes the value of the
// Carbon theme it is built on (v12-light white's, v12-dark g100's) unless the
// token gives it its own (`"v12-dark": …`), which is written in a rule of the
// v12 theme's own after the Carbon themes'. Run it after changing a
// tokens.json: `node packages/react/.storybook/proposals-css.mjs`.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const self = fileURLToPath(import.meta.url);
const here = dirname(self);

const header = `/* stylelint-disable lightness-notation, hue-degree-notation */
/* Generated by packages/react/.storybook/proposals-css.mjs from each v12
   component's proposals/tokens.json; never edit by hand.

   PREVIEW ONLY. These are PROPOSED tokens, not Carbon's. A component reads each one
   through get-var with a Carbon fallback, so without this file it renders Carbon's
   value — which is what a consumer gets. Load this to see what is being proposed. */
`;

const themes = {
  white: [
    ':root',
    "[data-carbon-theme='white']",
    '.cds--white',
    "[data-carbon-theme='v12-light']",
    '.cds--v12-light',
  ],
  g10: ["[data-carbon-theme='g10']", '.cds--g10'],
  g90: ["[data-carbon-theme='g90']", '.cds--g90'],
  g100: [
    "[data-carbon-theme='g100']",
    '.cds--g100',
    "[data-carbon-theme='v12-dark']",
    '.cds--v12-dark',
  ],
};

// A v12 theme's own selectors and the Carbon theme it is built on, whose rule
// above also covers it: its own rule holds only the tokens that give it a
// value of its own.
const v12 = {
  'v12-light': {
    base: 'white',
    selectors: ["[data-carbon-theme='v12-light']", '.cds--v12-light'],
  },
  'v12-dark': {
    base: 'g100',
    selectors: ["[data-carbon-theme='v12-dark']", '.cds--v12-dark'],
  },
};
const slots = [...Object.keys(themes), ...Object.keys(v12)];

const rule = (selectors, lines, indent) =>
  `${selectors.map((s) => indent + s).join(',\n')} {\n${lines.join('\n')}\n${indent}}\n`;

/**
 * proposals.scss for the components in a folder: each one's
 * proposals/tokens.json, in folder order.
 *
 * @param {string} components The folder of v12 components.
 * @returns {string} The stylesheet.
 */
export function proposalsCss(components) {
  // The declarations for each theme: plain values, and the OKLCH ones.
  const plain = Object.fromEntries(slots.map((t) => [t, []]));
  const oklch = Object.fromEntries(slots.map((t) => [t, []]));

  /** Adds one token's value in one theme to that theme's declarations. */
  const declare = (theme, name, value, fallback) => {
    if (value.startsWith('oklch')) {
      const hex = (fallback ?? value).toLowerCase();
      plain[theme].push(`  --cds-${name}: ${hex};`);
      oklch[theme].push(`    --cds-${name}: ${value};`);
    } else {
      const css = value.replace(/^\{(.+)\}$/, 'var(--cds-$1)').toLowerCase();
      plain[theme].push(`  --cds-${name}: ${css};`);
    }
  };

  /** Collects a token, or walks a group: `{ chat-input: { background: … } }`. */
  const collect = (node, name) => {
    if ('$type' in node) {
      const values = node.$extensions?.['carbon.themes'];
      const fallback = node.$extensions?.['com.ibm.harness.fallback'] ?? {};
      if (!values) return;
      for (const theme of Object.keys(themes)) {
        const value = values[theme];
        if (value != null) declare(theme, name, value, fallback[theme]);
      }
      for (const [theme, { base }] of Object.entries(v12)) {
        const value = values[theme];
        if (value != null && value !== values[base]) {
          declare(theme, name, value, fallback[theme]);
        }
      }
      return;
    }
    for (const [key, child] of Object.entries(node)) {
      if (!key.startsWith('$')) collect(child, name ? `${name}-${key}` : key);
    }
  };

  for (const folder of readdirSync(components).sort()) {
    const file = join(components, folder, 'proposals/tokens.json');
    if (existsSync(file)) collect(JSON.parse(readFileSync(file, 'utf8')), '');
  }

  /** Every theme's rule, then each v12 theme's own where it has declarations. */
  const rules = (decls, indent) =>
    [
      ...Object.keys(themes).map((t) => rule(themes[t], decls[t], indent)),
      ...Object.keys(v12)
        .filter((t) => decls[t].length)
        .map((t) => rule(v12[t].selectors, decls[t], indent)),
    ].join('\n');

  return (
    `${header}\n` +
    rules(plain, '') +
    '\n@supports (color: oklch(0 0 0)) {\n' +
    rules(oklch, '  ') +
    '}\n'
  );
}

if (process.argv[1] && resolve(process.argv[1]) === self) {
  writeFileSync(
    join(here, 'proposals.scss'),
    proposalsCss(join(here, '../src/v12/components'))
  );
}
