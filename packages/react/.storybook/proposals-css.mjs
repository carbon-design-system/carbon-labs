// Writes proposals.scss from every v12 component's proposals/tokens.json: each
// token's per-theme value (`carbon.themes`) as a custom property on the theme's
// selectors. An alias (`{layer-01}`) becomes `var(--cds-layer-01)`. An OKLCH
// value is written as its hex fallback (`com.ibm.harness.fallback`), then as
// OKLCH where the browser supports it. Run it after changing a tokens.json:
// `node packages/react/.storybook/proposals-css.mjs`.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const components = join(here, '../src/v12/components');
const out = join(here, 'proposals.scss');

const header = `/* stylelint-disable lightness-notation, hue-degree-notation */
/* Generated by packages/react/.storybook/proposals-css.mjs from each v12
   component's proposals/tokens.json; never edit by hand.

   PREVIEW ONLY. These are PROPOSED tokens, not Carbon's. A component reads each one
   through get-var with a Carbon fallback, so without this file it renders Carbon's
   value — which is what a consumer gets. Load this to see what is being proposed. */
`;

const themes = {
  white: [
    ':root',
    "[data-carbon-theme='white']",
    '.cds--white',
    "[data-carbon-theme='v12-light']",
    '.cds--v12-light',
  ],
  g10: ["[data-carbon-theme='g10']", '.cds--g10'],
  g90: ["[data-carbon-theme='g90']", '.cds--g90'],
  g100: [
    "[data-carbon-theme='g100']",
    '.cds--g100',
    "[data-carbon-theme='v12-dark']",
    '.cds--v12-dark',
  ],
};

// The declarations for each theme: plain values, and the OKLCH ones.
const plain = Object.fromEntries(Object.keys(themes).map((t) => [t, []]));
const oklch = Object.fromEntries(Object.keys(themes).map((t) => [t, []]));

/** Collects a token, or walks a group: `{ chat-input: { background: … } }`. */
function collect(node, name) {
  if ('$type' in node) {
    const values = node.$extensions?.['carbon.themes'];
    const fallback = node.$extensions?.['com.ibm.harness.fallback'] ?? {};
    if (!values) return;
    for (const theme of Object.keys(themes)) {
      const value = values[theme];
      if (value == null) continue;
      if (value.startsWith('oklch')) {
        const hex = (fallback[theme] ?? value).toLowerCase();
        plain[theme].push(`  --cds-${name}: ${hex};`);
        oklch[theme].push(`    --cds-${name}: ${value};`);
      } else {
        const css = value.replace(/^\{(.+)\}$/, 'var(--cds-$1)').toLowerCase();
        plain[theme].push(`  --cds-${name}: ${css};`);
      }
    }
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith('$')) collect(child, name ? `${name}-${key}` : key);
  }
}

for (const folder of readdirSync(components).sort()) {
  const file = join(components, folder, 'proposals/tokens.json');
  if (existsSync(file)) collect(JSON.parse(readFileSync(file, 'utf8')), '');
}

const rule = (selectors, lines, indent) =>
  `${selectors.map((s) => indent + s).join(',\n')} {\n${lines.join('\n')}\n${indent}}\n`;
const names = Object.keys(themes);

writeFileSync(
  out,
  `${header}\n` +
    names.map((t) => rule(themes[t], plain[t], '')).join('\n') +
    '\n@supports (color: oklch(0 0 0)) {\n' +
    names.map((t) => rule(themes[t], oklch[t], '  ')).join('\n') +
    '}\n'
);
