// Writes _index.scss from themes.json: Carbon's v12 `light` and `dark` themes
// as carbon#23376 generates them (packages/themes/src/dtcg/v12/themes.json at
// 9d4a73eee). Until @carbon/themes ships them, the v12 Storybook previews them
// this way. Each v12 theme is Carbon's nearest v11 theme (white, g100) with
// the tokens #23376 defines laid over it: a hex fallback, then OKLCH where the
// browser supports it. Delete this folder when @carbon/themes exports the
// v12 themes, and point the toolbar at them.
//
//   node packages/react/.storybook/v12-themes/generate.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { themes } = JSON.parse(readFileSync(join(here, 'themes.json'), 'utf8'));
const BASE = { light: 'white', dark: 'g100' };

const tokens = (node, path = []) =>
  node && typeof node === 'object' && '$value' in node
    ? [[path.join('-'), node]]
    : Object.entries(node ?? {})
        .filter(([key]) => !key.startsWith('$'))
        .flatMap(([key, child]) => tokens(child, [...path, key]));

// Written as labs's stylelint wants it: lightness as a percentage, hue in
// degrees, at most four decimals.
const round = (n, d) => Number(n.toFixed(d));
const oklch = ({ components: [l, c, h], alpha = 1 }) =>
  `oklch(${round(l * 100, 2)}% ${round(c, 4)} ${round(h, 2)}deg${
    alpha < 1 ? ` / ${round(alpha, 4)}` : ''
  })`;

let out = `//
// Copyright IBM Corp. 2026
//
// This source code is licensed under the Apache-2.0 license found in the
// LICENSE file in the root directory of this source tree.
//

// GENERATED by generate.mjs from themes.json (carbon#23376 @ 9d4a73eee). Do
// not edit. Carbon's v12 light and dark themes, previewed in the v12
// Storybook only, until @carbon/themes ships them.

@use '@carbon/styles' as styles;
`;

for (const [name, theme] of Object.entries(themes)) {
  const list = tokens(theme);
  const hex = list.map(([t, n]) => `  --cds-${t}: ${n.$value.hex};`).join('\n');
  const ok = list.map(([t, n]) => `    --cds-${t}: ${oklch(n.$value)};`).join('\n');
  out += `
[data-carbon-theme='v12-${name}'] {
  @include styles.theme(styles.$${BASE[name]});
${hex}

  @supports (color: oklch(0 0 0)) {
${ok}
  }
}
`;
}

writeFileSync(join(here, '_index.scss'), out);
console.log(`v12-themes: ${Object.keys(themes).join(', ')} written`);
