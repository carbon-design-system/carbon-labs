const art = (size: number) => (size === 16 ? ART[16] : ART[32]);

/** Settings' hover timing: enter and leave alike. */
export const SETTINGS_HOVER = { duration: DURATION, ease: EASING };

/**
 * Settings as frame geometry: the gear turned `TURN · h` about the centre (h
 * on Settings' own ease), the hub still; the 16px drawing scaled into the 32
 * grid. The status layer cuts the same drawing.
 */
export function settingsShapes({ h }: { h: number }, size?: number): Shapes {
  const a = art(size ?? 32);
  const k = size === 16 ? 'scale(2) ' : '';
  return {
    gear: {
      d: a.gear,
      transform: `${k}rotate(${+(TURN * h).toFixed(4)} ${a.pivot} ${a.pivot})`,
    },
    hub: { d: a.hub, transform: k.trim() || 'translate(0 0)' },
  };
}

export const SettingsSpec = /* @__PURE__ */ hoverIcon('Settings', {
  geo: settingsShapes,
  hover: SETTINGS_HOVER,
  leave: SETTINGS_HOVER,
  static: /* @__PURE__ */ carbonArt(Settings16, Settings32),
});
